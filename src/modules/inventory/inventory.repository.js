/**
 * Inventory Repository — Data Access Layer for Inventory Lots, Ledger & FEFO Queries
 * Source of truth: Blueprint §06.5, Phase 6
 *
 * @module modules/inventory/inventory.repository
 */

import { query } from '../../config/database.js'

export class InventoryRepository {
  // ─── LOTS ───────────────────────────────────────────
  async findLotByBatch(warehouseId, productId, batchNumber) {
    const { rows } = await query(
      `SELECT * FROM inventory_lots
        WHERE warehouse_id = $1 AND product_id = $2 AND batch_number = $3
        LIMIT 1`,
      [warehouseId, productId, batchNumber]
    )
    return rows[0] || null
  }

  async findLotById(lotId) {
    const { rows } = await query(`SELECT * FROM inventory_lots WHERE id = $1 LIMIT 1`, [lotId])
    return rows[0] || null
  }

  async createLot({ warehouse_id, product_id, batch_id = null, batch_number, expiry_date, quantity }) {
    const { rows } = await query(
      `INSERT INTO inventory_lots (warehouse_id, product_id, batch_id, batch_number, expiry_date, quantity_on_hand)
       VALUES ($1, $2, $3, $4, $5, $6)
       ON CONFLICT (warehouse_id, product_id, batch_number)
       DO UPDATE SET quantity_on_hand = inventory_lots.quantity_on_hand + EXCLUDED.quantity_on_hand, updated_at = NOW()
       RETURNING *`,
      [warehouse_id, product_id, batch_id, batch_number, expiry_date, quantity]
    )
    return rows[0]
  }

  /**
   * Manual vendor-batch backfill (§7.5.1 follow-up) — used when stock was
   * never received through the real Vendor Procurement pipeline (predates
   * it, or the vendor relationship isn't formalized as a `vendors` row
   * yet) but an admin still wants the batch/vendor/video recorded against
   * the shop product it belongs to. `batchNumber` is always server-
   * generated by the caller (a fresh `MANUAL-…` value) so this never
   * collides with, or silently merges into, a real procurement-linked lot
   * — plain INSERT, no ON CONFLICT.
   *
   * @param {import('pg').PoolClient} client — caller's transaction client
   * @returns {Promise<object>} the created lot row
   */
  async createManualLot(
    client,
    { warehouseId, productId, batchNumber, expiryDate, quantity, vendorName, videoUrl, notes, createdBy }
  ) {
    const { rows } = await client.query(
      `INSERT INTO inventory_lots
         (warehouse_id, product_id, batch_number, expiry_date, quantity_on_hand,
          is_manual_entry, manual_vendor_name, manual_video_url, manual_notes, created_by)
       VALUES ($1, $2, $3, $4, $5, true, $6, $7, $8, $9)
       RETURNING *`,
      [
        warehouseId,
        productId,
        batchNumber,
        expiryDate,
        quantity,
        vendorName,
        videoUrl || null,
        notes || null,
        createdBy || null,
      ]
    )
    return rows[0]
  }

  /**
   * Find available non-expired inventory lots ordered by FEFO (First Expiry First Out)
   * Spec §7.8.2, §11.11.6, §11.11.7
   *
   * @param {string} warehouseId
   * @param {string} productId
   * @param {object} [client] - DB transaction client for row locking
   * @returns {Promise<Array>}
   */
  async findAvailableLotsFefo(warehouseId, productId, client = null) {
    const dbClient = client || { query: (sql, params) => query(sql, params) }
    // Note: `inventory_lots` (migration 104) has no `state`/`version`
    // columns — an earlier version of this query referenced both and would
    // have thrown "column does not exist" the moment it was ever called;
    // it never was (reserveFefo has no callers), which is how this stayed
    // unnoticed. Fixed to match the real deployed schema.
    const { rows } = await dbClient.query(
      `SELECT * FROM inventory_lots
        WHERE warehouse_id = $1
          AND product_id = $2
          AND expiry_date > CURRENT_DATE
          AND (quantity_on_hand - quantity_reserved) > 0
        ORDER BY expiry_date ASC, created_at ASC
        FOR UPDATE SKIP LOCKED`,
      [warehouseId, productId]
    )
    return rows
  }

  /**
   * Atomic quantity guard update for inventory lot reservation
   * Spec §5.4.1, §7.8.2, §7.8.5
   *
   * @param {string} lotId
   * @param {number} deltaReserved
   * @param {object} [client] - DB transaction client
   * @returns {Promise<object|null>}
   */
  async reserveLotQuantityGuard(lotId, deltaReserved, client = null) {
    const dbClient = client || { query: (sql, params) => query(sql, params) }
    const { rows } = await dbClient.query(
      `UPDATE inventory_lots
          SET quantity_reserved = quantity_reserved + $2,
              updated_at = NOW()
        WHERE id = $1
          AND (quantity_on_hand - quantity_reserved) >= $2
        RETURNING *`,
      [lotId, deltaReserved]
    )
    return rows[0] || null
  }

  async updateLotQuantities(lotId, onHandChange, reservedChange, client = null) {
    const dbClient = client || { query: (sql, params) => query(sql, params) }
    const { rows } = await dbClient.query(
      `UPDATE inventory_lots
          SET quantity_on_hand = quantity_on_hand + $2,
              quantity_reserved = quantity_reserved + $3,
              updated_at = NOW()
        WHERE id = $1
        RETURNING *`,
      [lotId, onHandChange, reservedChange]
    )
    return rows[0]
  }

  // ─── LEDGER (APPEND-ONLY) ───────────────────────────
  /**
   * @param {object} [client] - DB transaction client. MUST be passed by any
   *   caller running inside an already-open transaction (e.g.
   *   `consumeForOrderItem`, called from `placeOrder`'s own transaction) —
   *   this insert writes to `stock_ledger_entries`, which references the
   *   very `inventory_lots` row that transaction's own prior UPDATE just
   *   locked. Defaulting to the bare pool `query()` here used to open a
   *   SECOND, unrelated connection for that insert while the first
   *   connection's transaction sat open uncommitted — that second
   *   connection would then block waiting on a lock the first one held,
   *   which could only ever be released by that same second query
   *   returning: a guaranteed self-deadlock, confirmed live in production
   *   (every `placeOrder` reaching this step hung forever, each one
   *   consuming another pool connection until the pool was exhausted).
   */
  async writeLedgerEntry({ lot_id, warehouse_id, product_id, movement_type, quantity_change, balance_after, reference_type = null, reference_id = null, actor_id = null }, client = null) {
    const dbClient = client || { query: (sql, params) => query(sql, params) }
    const { rows } = await dbClient.query(
      `INSERT INTO stock_ledger_entries (lot_id, warehouse_id, product_id, movement_type, quantity_change, balance_after, reference_type, reference_id, actor_id)
       VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9)
       RETURNING *`,
      [lot_id, warehouse_id, product_id, movement_type, quantity_change, balance_after, reference_type, reference_id, actor_id]
    )
    return rows[0]
  }

  async getLedgerEntries(warehouseId, productId = null) {
    const conditions = ['warehouse_id = $1']
    const params = [warehouseId]

    if (productId) {
      conditions.push('product_id = $2')
      params.push(productId)
    }

    const { rows } = await query(
      `SELECT e.*, l.batch_number, p.name AS product_name
         FROM stock_ledger_entries e
         JOIN inventory_lots l ON l.id = e.lot_id
         JOIN products p ON p.id = e.product_id
        WHERE ${conditions.join(' AND ')}
        ORDER BY e.created_at DESC`,
      params
    )
    return rows
  }

  // ─── RESERVATIONS ───────────────────────────────────
  async findReservationsByKey(reservationKey) {
    const { rows } = await query(
      `SELECT * FROM stock_reservations WHERE reservation_key = $1 AND status = 'RESERVED'`,
      [reservationKey]
    )
    return rows
  }

  async createReservation({ reservation_key, warehouse_id, product_id, lot_id, quantity_reserved, expires_at }) {
    const { rows } = await query(
      `INSERT INTO stock_reservations (reservation_key, warehouse_id, product_id, lot_id, quantity_reserved, status, expires_at)
       VALUES ($1, $2, $3, $4, $5, 'RESERVED', $6)
       RETURNING *`,
      [reservation_key, warehouse_id, product_id, lot_id, quantity_reserved, expires_at]
    )
    return rows[0]
  }

  async updateReservationStatus(reservationId, status) {
    const { rows } = await query(
      `UPDATE stock_reservations SET status = $2 WHERE id = $1 RETURNING *`,
      [reservationId, status]
    )
    return rows[0]
  }

  // ─── ADJUSTMENTS ────────────────────────────────────
  async createAdjustment(lotId, quantityChange, reason, actorId = null) {
    const { rows } = await query(
      `INSERT INTO stock_adjustments (lot_id, quantity_change, reason, actor_id)
       VALUES ($1, $2, $3, $4)
       RETURNING *`,
      [lotId, quantityChange, reason, actorId]
    )
    return rows[0]
  }

  /**
   * Directly consume on-hand quantity from a lot (no reservation phase) —
   * used when fulfilling an already-placed order line, not a pre-order
   * hold. Guards against taking more than is actually on hand.
   */
  async consumeLotOnHand(lotId, quantity, client = null) {
    const dbClient = client || { query: (sql, params) => query(sql, params) }
    const { rows } = await dbClient.query(
      `UPDATE inventory_lots
          SET quantity_on_hand = quantity_on_hand - $2,
              updated_at = NOW()
        WHERE id = $1
          AND quantity_on_hand >= $2
        RETURNING *`,
      [lotId, quantity]
    )
    return rows[0] || null
  }

  async insertOrderItemAllocation(client, { orderItemId, inventoryLotId, quantityAllocated }) {
    const dbClient = client || { query: (sql, params) => query(sql, params) }
    const { rows } = await dbClient.query(
      `INSERT INTO order_item_inventory_allocations (order_item_id, inventory_lot_id, quantity_allocated)
       VALUES ($1, $2, $3)
       RETURNING *`,
      [orderItemId, inventoryLotId, quantityAllocated]
    )
    return rows[0]
  }

  /**
   * Bulk-resolves the vendor-supply trace (supply order, vendor, quality
   * evidence) for a set of order_item ids that were allocated against
   * inventory lots at checkout — the chain the customer's invoice QR
   * ultimately resolves. One query for all items on an order rather than
   * N+1 per item.
   */
  async findQualityTraceForOrderItems(orderItemIds) {
    if (!orderItemIds || orderItemIds.length === 0) return []
    const { rows } = await query(
      `SELECT
         a.order_item_id,
         a.inventory_lot_id,
         a.quantity_allocated,
         so.id AS supply_order_id,
         so.supply_number,
         v.id AS vendor_id,
         v.name AS vendor_name,
         e.id AS evidence_id,
         e.media_url AS video_url,
         e.review_status AS evidence_review_status,
         e.created_at AS evidence_created_at
       FROM order_item_inventory_allocations a
       JOIN procurement_receipt_items pri ON pri.inventory_lot_id = a.inventory_lot_id
       JOIN procurement_receipts pr ON pr.id = pri.receipt_id
       JOIN procurement_supply_orders so ON so.id = pr.supply_order_id
       JOIN vendors v ON v.id = so.vendor_id
       LEFT JOIN procurement_evidence e
         ON e.supply_order_id = so.id
        AND e.evidence_type = 'QUALITY_VIDEO'
        AND e.review_status IS DISTINCT FROM 'REJECTED'
       WHERE a.order_item_id = ANY($1::uuid[])
       ORDER BY a.order_item_id, a.quantity_allocated DESC, e.created_at DESC`,
      [orderItemIds]
    )
    return rows
  }

  async listLots(warehouseId, productId = null) {
    const conditions = []
    const params = []

    // warehouseId is null for platform/admin callers with no X-Warehouse-Id
    // header (see warehouse-scope.js) — that means "all warehouses", not
    // "no warehouse", so it must not become a `= NULL` filter.
    if (warehouseId) {
      conditions.push(`warehouse_id = $${params.length + 1}`)
      params.push(warehouseId)
    }

    if (productId) {
      conditions.push(`product_id = $${params.length + 1}`)
      params.push(productId)
    }

    const where = conditions.length > 0 ? `WHERE ${conditions.join(' AND ')}` : ''

    // Real vendor/supply/video traceability for this lot, when it
    // originated from a vendor-procurement receipt (§ the vendor batch →
    // video linkage feature). A lot backfilled manually (migration 142,
    // `is_manual_entry`) has no procurement_receipt_item/supply_order to
    // join through at all — its vendor name and video URL live directly
    // on the lot row instead, so COALESCE falls back to those; a lot
    // created neither way (e.g. a raw stock correction) simply has NULLs
    // in both, not a fabricated vendor.
    const { rows } = await query(
      `SELECT l.*, p.name AS product_name, w.name AS warehouse_name, w.code AS warehouse_code,
              so.id AS supply_order_id, so.supply_number,
              COALESCE(v.id, NULL) AS vendor_id,
              COALESCE(v.name, l.manual_vendor_name) AS vendor_name,
              COALESCE(
                (SELECT e.media_url FROM procurement_evidence e
                  WHERE e.supply_order_id = so.id AND e.evidence_type = 'QUALITY_VIDEO'
                    AND e.review_status IS DISTINCT FROM 'REJECTED'
                  ORDER BY e.created_at DESC LIMIT 1),
                l.manual_video_url
              ) AS video_url
         FROM inventory_lots l
         JOIN products p ON p.id = l.product_id
         LEFT JOIN warehouses w ON w.id = l.warehouse_id
         LEFT JOIN procurement_receipt_items pri ON pri.inventory_lot_id = l.id
         LEFT JOIN procurement_receipts pr ON pr.id = pri.receipt_id
         LEFT JOIN procurement_supply_orders so ON so.id = pr.supply_order_id
         LEFT JOIN vendors v ON v.id = so.vendor_id
        ${where}
        ORDER BY l.expiry_date ASC`,
      params
    )
    return rows
  }
}
